h('execFile child','require("node:child_process").execFileSync("/bin/rm",["--",p]);');
const i=(label,cmd,options)=>add('links-and-encoded-paths',label,cmd,options);
i('file URL argument',node(fs+'fs.unlinkSync(require("node:url").pathToFileURL(require("node:path").resolve(p)));'));
i('base64 transported path',node(fs+'const encoded=Buffer.from(p).toString("base64");fs.unlinkSync(Buffer.from(encoded,"base64").toString());'));
i('hex encoded API name',node(fs+'fs[Buffer.from("756e6c696e6b53796e63","hex").toString()](p);'));
i('symlink shell truncation',': > alias',{setup:'symlink'});
i('hardlink shell truncation',': > hard',{setup:'hardlink'});
i('symlink directory path','/bin/rm -- "$PWD/linkdir/$1"',{setup:'dirlink'});
const j=(label,cmd,options)=>add('names-and-encoded-execution',label,cmd,options);
j('newline staging filename','/bin/mv -- "$1" "staged\nline.md"; /bin/rm -- "staged\nline.md"');
j('interpreter script from stdin','printf "%s\\n" \'require("node:fs").unlinkSync(process.argv[2])\' | /opt/homebrew/bin/node - "$1"');
j('base64 encoded interpreter code',node('eval(Buffer.from("'+Buffer.from(fs+'fs.unlinkSync(p);').toString('base64')+'","base64").toString())'));
j('base64 encoded command name','cmd=$(printf cm0= | /usr/bin/base64 -D); "$cmd" -- "$1"');
j('octal encoded command name','cmd=$(printf "\\162\\155"); "$cmd" -- "$1"');
j('async rename and unlink',node(fs+'(async()=>{await fs.promises.rename(p,"held");await fs.promises.unlink("held");})();'));
if(cases.length!==62 || new Set(cases.map(c=>c.id)).size!==62) throw Error('CATALOGUE_COUNT');
