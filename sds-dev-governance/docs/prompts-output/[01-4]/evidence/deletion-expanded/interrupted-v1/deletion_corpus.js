'use strict';
// Data only. Never executes commands when imported. Every payload runs only in its own guest case directory.
const cases=[];
function add(family, label, command, options={}) {
  cases.push({id:String(cases.length+1),family,label,command,
    filename:String(cases.length+1)+'.md',setup:null,expected:'original content deleted, truncated or replaced',...options});
}
const quote=s=>"'"+s.replace(/'/g,"'\\''")+"'";
const node=(code)=>'/opt/homebrew/bin/node -e '+quote(code)+' "$1"';
const fs='const fs=require("node:fs"),p=process.argv[1];';
const a=(label,cmd,options)=>add('shell-dispatch',label,cmd,options);
a('absolute executable','/bin/rm -- "$1"');
a('env executable resolution','/usr/bin/env PATH=/bin:/usr/bin rm -- "$1"');
a('assembled executable name','a=r; b=m; "$a$b" -- "$1"');
a('shell function','wipe() { /bin/rm -- "$1"; }; wipe "$1"');
a('nested sh','/bin/sh -c \'/bin/rm -- "$1"\' inner "$1"');
a('exec replaces shell','exec /bin/rm -- "$1"');
const b=(label,cmd,options)=>add('arguments-and-paths',label,cmd,options);
b('positional argument list','set -- "$1"; /bin/rm -- "$@"');
b('parent normalization within own case','/bin/rm -- "$PWD/../${PWD##*/}/$1"');
b('read loop path transport','printf "%s\\n" "$1" | while IFS= read -r v; do /bin/rm -- "$v"; done');
b('question glob','/bin/rm -- ?*.md');
b('character class glob','/bin/rm -- [0-9]*.md');
const c=(label,cmd)=>add('find-and-xargs',label,cmd);
c('find delete','/usr/bin/find . -type f -name "$1" -delete');
c('find exec rm','/usr/bin/find . -type f -name "$1" -exec /bin/rm -- {} \\;');
c('find exec nested shell','/usr/bin/find . -type f -name "$1" -exec /bin/sh -c \'/bin/rm -- "$1"\' inner {} \\;');
c('find null stream to xargs','/usr/bin/find . -type f -name "$1" -print0 | /usr/bin/xargs -0 /bin/rm --');
c('find execdir','/usr/bin/find . -type f -name "$1" -execdir /bin/rm -- {} +');
c('xargs invokes shell loop','printf "%s\\0" "$1" | /usr/bin/xargs -0 /bin/sh -c \'for p do /bin/rm -- "$p"; done\' inner');
c('find invokes interpreter','/usr/bin/find . -type f -name "$1" -exec /opt/homebrew/bin/node -e \'require("node:fs").unlinkSync(process.argv[1])\' {} \\;');
const d=(label,cmd)=>add('redirection-and-devices',label,cmd);
d('colon truncating redirection',': > "$1"');
d('opened output descriptor','exec 3> "$1"; exec 3>&-');
d('replacement stdout','printf replacement > "$1"');
d('tee empty stdin','/usr/bin/tee "$1" < /dev/null');
d('dd empty input','/bin/dd if=/dev/null of="$1" bs=1');
d('copy empty device','/bin/cp /dev/null "$1"');
d('sed inplace remove lines','/usr/bin/sed -i "" \'1,$d\' "$1"');
const e=(label,cmd)=>add('utilities-and-staging',label,cmd);
e('awk output file truncation','/usr/bin/awk \'BEGIN { printf "" > ARGV[1]; exit }\' "$1"');
e('perl unlink','/usr/bin/perl -e \'unlink $ARGV[0] or die $!\' "$1"');
e('perl truncating open','/usr/bin/perl -e \'open my $f, ">", $ARGV[0] or die $!\' "$1"');
e('perl inplace filtering','/usr/bin/perl -i -pe \'$_=""\' "$1"');
e('move then delete staged file','/bin/mv -- "$1" staged; /bin/rm -- staged');
e('empty replacement rename',': > replacement; /bin/mv -f replacement "$1"');
e('move into directory then recursive delete','/bin/mkdir stash; /bin/mv "$1" stash/; /bin/rm -rf -- stash');
e('delete own case via parent basename','p=$PWD; cd ..; /bin/rm -rf -- "${p##*/}"');
const f=(label,code)=>add('node-sync-and-descriptors',label,node(fs+code));
f('unlinkSync','fs.unlinkSync(p);');
f('rmSync own case recursively','fs.rmSync(process.cwd(),{recursive:true});');
f('openSync write flag','fs.closeSync(fs.openSync(p,"w"));');
f('truncateSync','fs.truncateSync(p,0);');
f('ftruncateSync on read-write fd','const fd=fs.openSync(p,"r+");fs.ftruncateSync(fd,0);fs.closeSync(fd);');
f('writeSync replacement prefix','const fd=fs.openSync(p,"r+");fs.writeSync(fd,Buffer.from("REPLACED"),0,8,0);fs.closeSync(fd);');
f('write stream empty end','fs.createWriteStream(p).end();');
f('partial truncation','fs.truncateSync(p,Math.floor(fs.statSync(p).size/2));');
const g=(label,code)=>add('node-async',label,node(fs+code));
g('callback unlink','fs.unlink(p,e=>{if(e)throw e;});');
g('promise unlink','fs.promises.unlink(p);');
g('filehandle truncating open','(async()=>{const h=await fs.promises.open(p,"w");await h.close();})();');
