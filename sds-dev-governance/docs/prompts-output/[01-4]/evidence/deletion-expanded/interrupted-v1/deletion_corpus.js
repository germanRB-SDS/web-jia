const h=(label,code)=>add('dynamic-dispatch-and-children',label,node(fs+code));
h('Reflect apply','Reflect.apply(fs.unlinkSync,fs,[p]);');
h('Function constructor','Function("fs","p","fs.unlinkSync(p)")(fs,p);');
h('vm context API dispatch','require("node:vm").runInNewContext("fs.unlinkSync(p)",{fs,p});');
